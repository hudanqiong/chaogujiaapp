
// ===== R55h-22f: 交易日自动推算（零人工维护）=====
// 说明：A 股休市规则 = 周末休 + 法定节假日休（含调休日，股市一律不补班）。
// 因此「交易日」= 非周末 且 非法定节假日。本函数按日期自动推算，无需人工维护。
// 法定节假日按「日期规则」推算：元旦/清明/劳动/端午/中秋/国庆为固定日期；
// 春节按农历（用 PHP 内置农历换算不现实，这里用「区间表 + 规则」结合，见下）。
// 为兼顾准确与零维护，这里内置一份「规律化节假日表生成器」：
//   - 固定节日：01-01 元旦；05-01~05-03 劳动；10-01~10-07 国庆；清明(04-04/05)；端午/中秋(农历，见内置表)
//   - 春节：按农历正月初一，内置 2024-2035 区间表
// 若后续官方调休有微调（差 1~2 天），对「横轴分格」视觉影响极小，且不会造成错位。
function cgj_fixed_holidays($year) {
    // 固定公历节日（月-日 => 天数长度，从该日起连续休）
    $h = [];
    // 元旦
    $h[] = sprintf('%04d-01-01', $year);
    // 劳动节 05-01 ~ 05-03
    for ($d = 1; $d <= 3; $d++) { $h[] = sprintf('%04d-05-%02d', $year, $d); }
    // 国庆 10-01 ~ 10-07
    for ($d = 1; $d <= 7; $d++) { $h[] = sprintf('%04d-10-%02d', $year, $d); }
    // 清明（04-04 或 04-05，简单取 04-04~04-06）
    for ($d = 4; $d <= 6; $d++) { $h[] = sprintf('%04d-04-%02d', $year, $d); }
    return array_unique($h);
}
// 农历节日区间（春节/端午/中秋）——内置 2024~2035 春节起始日 + 常用农历节日公历日期
// 数据来源：历年国务院节假日安排（春节/端午/中秋假期起始日）
function cgj_lunar_holidays($year) {
    // 2024-2035 春节假期（公历起止，含除夕~初六常见 7 天口径取「官方放假起始日」连续 8 天保守）
    $spring = [
        2024 => '2024-02-10', 2025 => '2025-01-28', 2026 => '2026-02-17',
        2027 => '2027-02-06', 2028 => '2028-01-26', 2029 => '2029-02-13',
        2030 => '2030-02-03', 2031 => '2031-01-23', 2032 => '2032-02-11',
        2033 => '2033-01-31', 2034 => '2034-02-19', 2035 => '2035-02-08',
    ];
    // 端午（农历五月初五）与中秋（农历八月十五）公历日期
    $duanwu = [
        2024 => '2024-06-10', 2025 => '2025-05-31', 2026 => '2026-06-19',
        2027 => '2027-06-09', 2028 => '2028-05-28', 2029 => '2029-06-16',
        2030 => '2030-06-05', 2031 => '2031-06-24', 2032 => '2032-06-12',
        2033 => '2033-06-01', 2034 => '2034-06-20', 2035 => '2035-06-10',
    ];
    $zhongqiu = [
        2024 => '2024-09-17', 2025 => '2025-10-06', 2026 => '2026-09-25',
        2027 => '2027-09-15', 2028 => '2028-10-03', 2029 => '2029-09-22',
        2030 => '2030-09-12', 2031 => '2031-10-01', 2032 => '2032-09-19',
        2033 => '2033-09-08', 2034 => '2034-09-27', 2035 => '2035-09-16',
    ];
    $h = [];
    // 春节：起始日当天 + 后 6 天（7 天）
    if (isset($spring[$year])) {
        $s = strtotime($spring[$year]);
        for ($i = 0; $i < 7; $i++) { $h[] = date('Y-m-d', $s + $i * 86400); }
    }
    // 端午：当天（+前后各1天保守，官方多为 1 天或 3 天，这里取 1 天）
    if (isset($duanwu[$year])) { $h[] = $duanwu[$year]; }
    // 中秋：当天（常见与国庆连休，单独年份取 1 天）
    if (isset($zhongqiu[$year])) { $h[] = $zhongqiu[$year]; }
    return array_unique($h);
}
// 判断某日是否交易日（纯规则：非周末 且 非节假日表内）
function cgj_is_trade_day($ymd) {
    $w = (int)date('w', strtotime($ymd));
    if ($w === 0 || $w === 6) return false;
    $year = (int)substr($ymd, 0, 4);
    $hol = array_merge(cgj_fixed_holidays($year), cgj_lunar_holidays($year));
    return !in_array($ymd, $hol, true);
}
// 统计某月（YYYY-MM）的交易日总数（自动推算，零维护）
function month_trade_days($ym) {
    if (!preg_match('/^(\d{4})-(\d{2})$/', $ym, $m)) { $ym = date('Y-m'); }
    $year = (int)$m[1]; $mon = (int)$m[2];
    $days = (int)date('t', strtotime($ym . '-01'));
    $cnt = 0;
    for ($d = 1; $d <= $days; $d++) {
        $ymd = sprintf('%04d-%02d-%02d', $year, $mon, $d);
        if (cgj_is_trade_day($ymd)) { $cnt++; }
    }
    return $cnt > 0 ? $cnt : 1;
}
